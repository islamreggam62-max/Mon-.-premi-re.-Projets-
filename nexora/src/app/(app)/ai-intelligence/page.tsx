import type { Metadata } from "next";
import {
  Sparkles,
  ShieldAlert,
  TrendingUp,
  Gauge,
  Lightbulb,
  Lock,
} from "lucide-react";
import { PageHeader } from "@/components/ui/page-header";
import { Card, CardHeader, CardBody } from "@/components/ui/card";
import { Badge, type BadgeTone } from "@/components/ui/badge";
import { Progress } from "@/components/ui/progress";
import { type AiInsight } from "@/lib/demo-data";
import { getAiInsights } from "@/lib/data";
import type { LucideIcon } from "lucide-react";

export const metadata: Metadata = { title: "AI Intelligence" };

const categoryMeta: Record<
  AiInsight["category"],
  { tone: BadgeTone; icon: LucideIcon }
> = {
  Risk: { tone: "danger", icon: ShieldAlert },
  Opportunity: { tone: "success", icon: Lightbulb },
  Efficiency: { tone: "info", icon: Gauge },
  Forecast: { tone: "brand", icon: TrendingUp },
};

export default async function AiIntelligencePage() {
  const aiInsights = await getAiInsights();
  return (
    <div className="space-y-6">
      <PageHeader
        title="AI Intelligence"
        description="Where NEXORA will surface risks, opportunities and recommendations across your operations."
        showDemoTag
      />

      {/* Hard, unmissable disclosure */}
      <div className="nx-card nx-sheen overflow-hidden">
        <div className="flex flex-col gap-4 p-5 sm:flex-row sm:items-center">
          <span className="flex h-12 w-12 shrink-0 items-center justify-center rounded-2xl bg-brand-gradient shadow-glow-sm">
            <Sparkles className="h-6 w-6 text-white" />
          </span>
          <div className="flex-1">
            <h2 className="text-base font-semibold text-foreground">
              No AI model is connected yet
            </h2>
            <p className="mt-1 text-sm leading-relaxed text-muted">
              Everything below is hand-written placeholder content that shows
              how insights will be presented. Nothing here is generated by a
              model, and no data leaves your browser. A real inference engine is
              planned for a later phase.
            </p>
          </div>
          <Badge tone="brand" className="self-start sm:self-center">
            Preview
          </Badge>
        </div>
      </div>

      {/* Prompt surface — intentionally disabled */}
      <Card sheen>
        <CardBody>
          <div className="flex items-center gap-2 text-sm text-subtle">
            <Lock className="h-4 w-4" />
            Ask NEXORA (available after AI integration)
          </div>
          <div className="mt-3 flex flex-col gap-2 sm:flex-row">
            <input
              disabled
              placeholder="e.g. Which projects are most at risk this quarter?"
              aria-label="AI prompt (disabled in Phase 1)"
              className="h-11 flex-1 cursor-not-allowed rounded-xl border border-border bg-surface-2/50 px-4 text-sm text-foreground placeholder:text-subtle"
            />
            <button
              disabled
              className="h-11 cursor-not-allowed rounded-xl bg-brand-gradient px-5 text-sm font-medium text-white opacity-50"
            >
              Generate
            </button>
          </div>
        </CardBody>
      </Card>

      {/* Insight cards */}
      <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        {aiInsights.map((insight) => {
          const meta = categoryMeta[insight.category];
          const Icon = meta.icon;
          return (
            <Card key={insight.id} sheen>
              <CardHeader
                title={
                  <span className="flex items-center gap-2">
                    <Icon className="h-4 w-4 text-violet-300" />
                    {insight.category}
                  </span>
                }
                action={<Badge tone={meta.tone}>{insight.category}</Badge>}
              />
              <CardBody>
                <p className="text-sm font-semibold leading-snug text-foreground">
                  {insight.title}
                </p>
                <p className="mt-2 text-sm leading-relaxed text-muted">
                  {insight.detail}
                </p>
                <div className="mt-4">
                  <div className="flex items-center justify-between text-xs text-subtle">
                    <span>Confidence (illustrative, not computed)</span>
                    <span className="font-medium text-muted">
                      {insight.confidence}%
                    </span>
                  </div>
                  <Progress value={insight.confidence} className="mt-1.5" />
                </div>
              </CardBody>
            </Card>
          );
        })}
      </div>
    </div>
  );
}
